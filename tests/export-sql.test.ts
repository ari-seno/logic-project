import { describe, expect, it } from "vitest";

import { domainsToSql, toSnake } from "@/lib/export/sql";
import { makeBundle, makeEmptyBundle } from "./fixtures/project-bundle";

const GENERATED_AT = "2026-02-02T00:00:00.000Z";

describe("toSnake", () => {
  it("converts camelCase and spaces to snake_case", () => {
    expect(toSnake("BookLoan")).toBe("book_loan");
    expect(toSnake("Book Loan")).toBe("book_loan");
    expect(toSnake("ISBN")).toBe("isbn");
  });

  it("falls back when the name has no usable characters", () => {
    expect(toSnake("###", "entity")).toBe("entity");
  });

  it("prefixes identifiers that start with a digit", () => {
    expect(toSnake("2fa")).toBe("t_2fa");
  });
});

describe("domainsToSql", () => {
  it("creates a table per entity with mapped column types", () => {
    const sql = domainsToSql(makeBundle(), { generatedAt: GENERATED_AT });
    expect(sql).toContain("CREATE TABLE book (");
    expect(sql).toContain("CREATE TABLE member (");
    expect(sql).toContain("id uuid PRIMARY KEY DEFAULT gen_random_uuid()");
    expect(sql).toContain("title varchar(255) NOT NULL");
  });

  it("marks optional columns as NULL", () => {
    const sql = domainsToSql(makeBundle(), { generatedAt: GENERATED_AT });
    expect(sql).toContain("isbn varchar(255) NULL");
  });

  it("places a one_to_many foreign key on the target table", () => {
    const sql = domainsToSql(makeBundle(), { generatedAt: GENERATED_AT });
    expect(sql).toContain("ALTER TABLE book");
    expect(sql).toContain("FOREIGN KEY (member_id) REFERENCES member (id)");
    expect(sql).toContain("CREATE INDEX idx_book_member_id ON book (member_id);");
  });

  it("emits a join table for many_to_many relationships", () => {
    const bundle = makeBundle();
    bundle.relationships = [
      {
        ...bundle.relationships[0],
        relationship_type: "many_to_many",
        name: "book_tags",
      },
    ];
    const sql = domainsToSql(bundle, { generatedAt: GENERATED_AT });
    expect(sql).toContain("CREATE TABLE book_tags (");
    expect(sql).toContain("PRIMARY KEY (");
    expect(sql).toContain("ON DELETE CASCADE");
  });

  it("adds comments for entity and attribute descriptions", () => {
    const sql = domainsToSql(makeBundle(), { generatedAt: GENERATED_AT });
    expect(sql).toContain(
      "COMMENT ON TABLE book IS 'A book in the catalog.';",
    );
    expect(sql).toContain("COMMENT ON COLUMN book.title IS 'Book title';");
  });

  it("notes the absence of a primary key", () => {
    const bundle = makeBundle();
    bundle.attributes = bundle.attributes.map((a) => ({
      ...a,
      is_primary_key: false,
    }));
    const sql = domainsToSql(bundle, { generatedAt: GENERATED_AT });
    expect(sql).toContain("no primary key declared");
    expect(sql).not.toContain("PRIMARY KEY");
  });

  it("disambiguates duplicate table names", () => {
    const bundle = makeBundle();
    bundle.entities = [
      bundle.entities[0],
      { ...bundle.entities[1], name: "Book" },
    ];
    const sql = domainsToSql(bundle, { generatedAt: GENERATED_AT });
    expect(sql).toContain("CREATE TABLE book (");
    expect(sql).toContain("CREATE TABLE book_2 (");
  });

  it("includes a header with the project name", () => {
    const sql = domainsToSql(makeBundle(), { generatedAt: GENERATED_AT });
    expect(sql).toContain("-- project: Library Management System");
    expect(sql).toContain(`-- generated: ${GENERATED_AT}`);
  });

  it("returns only the header for an empty bundle", () => {
    const sql = domainsToSql(makeEmptyBundle(), { generatedAt: GENERATED_AT });
    expect(sql).toContain("PostgreSQL DDL generated by Logic Project");
    expect(sql).not.toContain("CREATE TABLE");
  });

  it("is deterministic for the same input", () => {
    const a = domainsToSql(makeBundle(), { generatedAt: GENERATED_AT });
    const b = domainsToSql(makeBundle(), { generatedAt: GENERATED_AT });
    expect(a).toBe(b);
  });
});
