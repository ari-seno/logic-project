import { strToU8, zipSync } from "fflate";

import type { ProjectBundle } from "@/lib/export/bundle";
import {
  buildExportFile,
  EXPORT_FORMATS,
  type ExportFileOptions,
} from "@/lib/export/download";
import { slugify } from "@/lib/utils";

export const EXPORT_ARCHIVE_FORMAT = "zip";

export const EXPORT_ARCHIVE_CONTENT_TYPE = "application/zip";

/** Formats accepted by the download endpoint, including the archive. */
export const EXPORT_DOWNLOAD_FORMATS = [
  ...EXPORT_FORMATS,
  EXPORT_ARCHIVE_FORMAT,
] as const;

export interface ExportArchive {
  content: Uint8Array;
  contentType: string;
  filename: string;
}

function readmeFor(
  bundle: ProjectBundle,
  filenames: string[],
  options: ExportFileOptions,
): string {
  const lines = [
    `# ${bundle.project.name} — export bundle`,
    "",
    bundle.project.description?.trim() || "(no description)",
    "",
    "## Files",
    "",
    ...filenames.map((name) => `/ ${name}`),
    "",
    options.generatedAt
      ? `Generated at ${options.generatedAt} by Logic Project.`
      : "Generated by Logic Project.",
  ];

  return lines.join("\n");
}

/**
 * Renders every single-file export format and packs them into one zip archive.
 * The files are byte-identical to the ones served by the download endpoint.
 */
export function buildExportArchive(
  bundle: ProjectBundle,
  options: ExportFileOptions = {},
): ExportArchive {
  const files: Record<string, Uint8Array> = {};

  for (const format of EXPORT_FORMATS) {
    const file = buildExportFile(bundle, format, options);
    files[file.filename] = strToU8(file.content);
  }

  files["README.md"] = strToU8(readmeFor(bundle, Object.keys(files), options));

  const content = zipSync(files, { level: 6 });

  return {
    content,
    contentType: EXPORT_ARCHIVE_CONTENT_TYPE,
    filename: `${slugify(bundle.project.name, "project")}-export.zip`,
  };
}
